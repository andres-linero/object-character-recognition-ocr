"""Export the initial PostgreSQL DDL from the canonical SQLAlchemy model."""
from pathlib import Path
import sys
from sqlalchemy import create_mock_engine
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ADK_Agentic.storage import metadata

statements = ["-- Generated by scripts/export_schema.py; storage.py is the canonical migration model."]
statements.extend(f"CREATE SCHEMA IF NOT EXISTS {name};" for name in ("staging", "core", "ops"))
engine = create_mock_engine("postgresql+psycopg://", lambda sql, *a, **kw: statements.append(str(sql.compile(dialect=engine.dialect)).strip() + ";"))
metadata.create_all(engine, checkfirst=False)
if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "database/001_initial.sql"
    target.write_text("\n\n".join(statements) + "\n")
    print(target)
